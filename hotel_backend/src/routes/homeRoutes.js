const express = require('express');
const homeController = require('../controllers/homeController');
const serviceController = require('../controllers/serviceController');
const promotionController = require('../controllers/promotionController');
const amenityController = require('../controllers/amenityController');
const roomTypeController = require('../controllers/roomTypeController');
const equipmentItemController = require('../controllers/equipmentItemController');
const { requireAdmin, requirePromotionReadAccess } = require('../middlewares/roleMiddleware');

const router = express.Router();
router.get('/home', homeController.getHomeData);
router.get('/room-types', homeController.getRoomTypes);
router.get('/room-types/:roomTypeId', homeController.getRoomTypeDetails);
router.get('/admin/amenities', requireAdmin, amenityController.getAdminAmenities);
router.get('/admin/equipment-items', requireAdmin, equipmentItemController.getEquipmentItems);
router.get('/admin/equipment-items/:id', requireAdmin, equipmentItemController.getEquipmentItemById);
router.get('/admin/equipment-items/:id/rooms', requireAdmin, equipmentItemController.getEquipmentRooms);
router.put('/admin/equipment-items/:id/rooms', requireAdmin, equipmentItemController.assignEquipmentToRooms);
router.post('/admin/equipment-items', requireAdmin, equipmentItemController.createEquipmentItem);
router.put('/admin/equipment-items/:id', requireAdmin, equipmentItemController.updateEquipmentItem);
router.delete('/admin/equipment-items/:id', requireAdmin, equipmentItemController.deleteEquipmentItem);
router.post('/room-types', requireAdmin, roomTypeController.createRoomType);
router.put('/room-types/:roomTypeId', requireAdmin, roomTypeController.updateRoomType);
router.delete('/room-types/:roomTypeId', requireAdmin, roomTypeController.deleteRoomType);
router.get('/promotions/active', homeController.getPromotions);
router.post('/promotions/validate', promotionController.validatePromotion);
router.get('/promotions', requirePromotionReadAccess, promotionController.getPromotions);
router.get('/promotions/:id', requirePromotionReadAccess, promotionController.getPromotionById);
router.get('/admin/promotions', requirePromotionReadAccess, promotionController.getPromotions);
router.get('/admin/promotions/:id', requirePromotionReadAccess, promotionController.getPromotionById);
router.post('/admin/promotions', requireAdmin, promotionController.createPromotion);
router.put('/admin/promotions/:id', requireAdmin, promotionController.updatePromotion);
router.delete('/admin/promotions/:id', requireAdmin, promotionController.deletePromotion);
router.get('/services', homeController.getServices);
router.get('/services/:id', homeController.getActiveServiceById);
router.get('/admin/services', requireAdmin, serviceController.getServices);
router.get('/admin/services/:id', requireAdmin, serviceController.getServiceById);
router.post('/admin/services', requireAdmin, serviceController.createService);
router.put('/admin/services/:id', requireAdmin, serviceController.updateService);
router.delete('/admin/services/:id', requireAdmin, serviceController.deleteService);
module.exports = router;
